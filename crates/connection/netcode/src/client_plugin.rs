// We process bytes from the link and re-add them to the link so that the Transport can still
// fetch directly from the link
impl NetcodeClientPlugin {
    /// Takes packets from the Link, process them through netcode
    /// and buffer them back into the link to be sent by the IO
    fn send(
        mut query: Query<(&mut Link, &mut NetcodeClient), (With<Linked>, Without<HostClient>)>,
    ) {
        adaptive_for_each_mut!(query).for_each(|(mut link, mut client)| {
            // send user packets
            for _ in 0..link.send.len() {
                if let Some(payload) = link.send.pop() {
                    client
                        .inner
                        .send(payload, &mut link.send)
                        .inspect_err(|e| {
                            error!("Error sending packet: {:?}", e);
                        })
                        .ok();
                }
            }

            // send netcode internal packets
            client.inner.drain_send_netcode_packets(&mut link.send);

            // #[cfg(feature = "test_utils")]
            // trace!("CLIENT: length of each packet in send: {:?}", link.send.iter().map(|p| p.len()).collect::<Vec<_>>());
        })
    }

    /// Receive packets from the Link, and process them through the client,
    /// then buffer them back into the Link
    fn receive(
        real_time: Res<Time<Real>>,
        mut query: Query<
            (
                Entity,
                &mut Link,
                &mut NetcodeClient,
                Has<Connecting>,
                Has<Disconnected>,
            ),
            (With<Linked>, Without<HostClient>),
        >,
        parallel_commands: ParallelCommands,
    ) {
        let delta = real_time.delta();
        adaptive_for_each_mut!(query).for_each(
            |(entity, mut link, mut client, connecting, disconnected)| {
                // #[cfg(feature = "test_utils")]
                // trace!("CLIENT: length of each packet in receive: {:?}", link.recv.iter().map(|p| p.len()).collect::<Vec<_>>());

                // Buffer the packets received from the link into the Connection
                // don't short-circuit on error
                if let Ok(state) = client
                    .inner
                    .try_update(delta.as_secs_f64(), &mut link.recv)
                    .inspect_err(|e| {
                        error!("Error receiving packet: {:?}", e);
                    })
                {
                    if state == ClientState::Connected && connecting {
                        info!("Client {} connected", client.id());
                        parallel_commands.command_scope(|mut commands| {
                            let local = LocalId(client.id());
                            commands.queue(move |world: &mut World| {
                                Self::admit_connection(world, entity, local);
                            });
                        });
                    }
                    if !disconnected
                        && !matches!(
                            state,
                            ClientState::Connected
                                | ClientState::SendingConnectionRequest
                                | ClientState::SendingChallengeResponse
                        )
                    {
                        info!("Client {} disconnected. State: {state:?}", client.id());
                        parallel_commands.command_scope(|mut commands| {
                            commands.entity(entity).insert(Disconnected {
                                reason: match state {
                                    ClientState::Disconnected => DisconnectedReason::ByPeer(None),
                                    _ => DisconnectedReason::TransportError(format!("{state:?}")),
                                },
                            });
                        });
                    }
                }
            },
        )
    }

    fn admit_connection(world: &mut World, entity: Entity, local: LocalId) {
        let mismatch = world
            .get::<LocalId>(entity)
            .is_some_and(|requested| *requested != local)
            || world
                .get::<RemoteId>(entity)
                .is_some_and(|requested| requested.0 != PeerId::SERVER);
        if local.0 == PeerId::SERVER {
            reject(world, entity, format!("{}", Error::ReservedClientId));
        } else if mismatch {
            reject(
                world,
                entity,
                format!(
                    "requested identity does not match authenticated netcode identity {:?}",
                    local.0
                ),
            );
        } else if admit(world, entity, local, RemoteId(PeerId::SERVER), ()) {
            return;
        }
        if let Some(mut client) = world.get_mut::<NetcodeClient>(entity) {
            if !client.inner.is_disconnected() {
                let _ = client.inner.disconnect();
            }
        }
    }

    fn connect(
        trigger: On<Connect>,
        mut commands: Commands,
        query: Query<(), (With<NetcodeClient>, Without<Connected>)>,
    ) {
        if query.get(trigger.entity).is_ok() {
            let entity = trigger.entity;
            commands.queue(move |world: &mut World| {
                let token_id = world
                    .get::<NetcodeClient>(entity)
                    .and_then(|client| client.token_client_id);
                if let (Some(token_id), Some(requested)) = (token_id, world.get::<LocalId>(entity))
                {
                    if requested.0 != PeerId(token_id) {
                        let reason = format!(
                            "requested local ID {:?} does not match netcode token ID {token_id}",
                            requested.0
                        );
                        reject(world, entity, reason);
                        return;
                    }
                }
                debug!("Starting netcode connection process");
                world
                    .get_mut::<NetcodeClient>(entity)
                    .unwrap()
                    .inner
                    .connect();
                world.entity_mut(entity).insert(Connecting);
            });
        }
    }

    fn disconnect(
        trigger: On<Disconnect>,
        mut commands: Commands,
        mut query: Query<&mut NetcodeClient, Without<Disconnected>>,
    ) -> Result {
        if let Ok(mut client) = query.get_mut(trigger.entity) {
            client.inner.disconnect()?;
            commands.entity(trigger.entity).insert(Disconnected {
                reason: DisconnectedReason::UserRequested(None),
            });
        }
        Ok(())
    }

    fn disconnected(trigger: On<Insert, Disconnected>, mut query: Query<&mut NetcodeClient>) {
        if let Ok(mut client) = query.get_mut(trigger.entity) {
            if !client.inner.is_disconnected() {
                let _ = client.inner.disconnect();
            }
        }
    }
}

impl Plugin for NetcodeClientPlugin {
    fn build(&self, app: &mut App) {
        if !app.is_plugin_added::<ConnectionPlugin>() {
            app.add_plugins(ConnectionPlugin);
        }
        app.configure_sets(
            PreUpdate,
            (
                LinkSystems::Receive,
                ConnectionSystems::Receive,
                TransportSystems::Receive,
            )
                .chain(),
        );
        app.configure_sets(
            PostUpdate,
            (
                TransportSystems::Send,
                ConnectionSystems::Send,
                LinkSystems::Send,
            )
                .chain(),
        );

        app.add_systems(PreUpdate, Self::receive.in_set(ConnectionSystems::Receive));
        app.add_systems(PostUpdate, Self::send.in_set(ConnectionSystems::Send));
        app.add_observer(Self::connect);
        app.add_observer(Self::disconnect);
        app.add_observer(Self::disconnected);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::packet::{ChallengePacket, KeepAlivePacket};
    use crate::token::ChallengeToken;

    #[test]
    fn manual_authentication_rejects_reserved_client_id() {
        assert!(matches!(
            NetcodeClient::new(
                Authentication::Manual {
                    server_addr: "127.0.0.1:5000".parse().unwrap(),
                    client_id: 0,
                    private_key: [0; crate::PRIVATE_KEY_BYTES],
                    protocol_id: 1,
                },
                NetcodeConfig::default(),
            ),
            Err(Error::ReservedClientId)
        ));
    }

    #[test]
    fn opaque_token_checks_requested_id_before_admission() {
        let token =
            crate::ConnectToken::build("127.0.0.1:5000", 1, 7, [0; crate::PRIVATE_KEY_BYTES])
                .generate()
                .unwrap();
        let key = token.server_to_client_key;
        let mut app = App::new();
        app.init_resource::<Time<Real>>();
        app.add_plugins(NetcodeClientPlugin);
        let entity = app
            .world_mut()
            .spawn((
                NetcodeClient::new(Authentication::Token(token), NetcodeConfig::default()).unwrap(),
                LocalId(PeerId(8)),
            ))
            .id();
        app.world_mut().flush();
        app.world_mut().trigger(Connect { entity });
        app.world_mut().flush();
        app.world_mut().entity_mut(entity).insert(Linked);
        for (sequence, packet) in [
            ChallengePacket::create(0, [0; ChallengeToken::SIZE]),
            KeepAlivePacket::create(7),
        ]
        .into_iter()
        .enumerate()
        {
            let mut buf = [0; crate::MAX_PKT_BUF_SIZE];
            let len = packet.write(&mut buf, sequence as u64, &key, 1).unwrap();
            app.world_mut()
                .get_mut::<Link>(entity)
                .unwrap()
                .recv
                .push_raw(bytes::BytesMut::from(&buf[..len]));
        }
        app.update();

        assert!(app.world().get::<Connected>(entity).is_none());
        assert!(
            app.world()
                .get::<NetcodeClient>(entity)
                .unwrap()
                .inner
                .is_disconnected()
        );
        assert_eq!(app.world().get::<LocalId>(entity).unwrap().0, PeerId(8));
        assert!(matches!(
            app.world().get::<Disconnected>(entity).unwrap().reason,
            DisconnectedReason::TransportError(_)
        ));
    }

    #[test]
    fn manual_token_rejects_requested_id_before_handshake() {
        let mut app = App::new();
        app.add_plugins(NetcodeClientPlugin);
        let entity = app
            .world_mut()
            .spawn((
                NetcodeClient::new(
                    Authentication::Manual {
                        server_addr: "127.0.0.1:5000".parse().unwrap(),
                        client_id: 7,
                        private_key: [0; crate::PRIVATE_KEY_BYTES],
                        protocol_id: 1,
                    },
                    NetcodeConfig::default(),
                )
                .unwrap(),
                LocalId(PeerId(8)),
            ))
            .id();
        app.world_mut().flush();
        app.world_mut().trigger(Connect { entity });
        app.world_mut().flush();

        assert!(
            !app.world()
                .get::<NetcodeClient>(entity)
                .unwrap()
                .inner
                .is_pending()
        );
        assert!(app.world().get::<Connected>(entity).is_none());
        assert!(app.world().get::<Connecting>(entity).is_none());
        assert_eq!(app.world().get::<LocalId>(entity).unwrap().0, PeerId(8));
        assert!(matches!(
            app.world().get::<Disconnected>(entity).unwrap().reason,
            DisconnectedReason::TransportError(_)
        ));
    }
}
