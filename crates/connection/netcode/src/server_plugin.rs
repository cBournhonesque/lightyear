pub struct NetcodeServerPlugin;

/// Retire accepted entities only after the frame's deferred link-state cleanup has settled.
#[derive(Component)]
struct RetireNetcodeLink;

/// An error encountered while processing incoming netcode traffic for a server-side client link.
#[derive(Message, Debug)]
pub struct NetcodeServerError {
    /// The server entity that encountered the error.
    pub server_entity: Entity,
    /// The client link entity associated with the packet or payload.
    pub client_entity: Entity,
    /// The underlying netcode error.
    pub error: crate::Error,
}

/// User data extracted from the client's connection token.
/// Contains up to 256 bytes of custom data embedded by the token issuer.
#[derive(Component, Debug, Clone)]
pub struct TokenUserData(pub [u8; USER_DATA_BYTES]);

#[derive(Default)]
pub(crate) struct NetcodeServerContext {
    pub(crate) connections: Vec<(ClientId, Entity, [u8; USER_DATA_BYTES])>,
    pub(crate) disconnections: Vec<(ClientId, Entity)>,
}

#[derive(Component)]
#[require(Server, NoDefaultConnection)]
pub struct NetcodeServer {
    pub(crate) inner: crate::server::Server<NetcodeServerContext>,
}

// TODO: should be part of the NetcodeServer component
#[derive(Debug, Clone)]
pub struct NetcodeConfig {
    /// Maximum number of simultaneous client connections accepted by the server.
    pub max_clients: usize,
    pub num_disconnect_packets: usize,
    pub keep_alive_send_rate: f64,
    /// Set the duration (in seconds) after which the server disconnects a client if they don't hear from them.
    /// This is valid for tokens generated by the server.
    /// The default is 3 seconds. A negative value means no timeout.
    pub client_timeout_secs: i32,
    pub protocol_id: u64,
    pub private_key: Key,
    /// Socket addresses accepted during private connect-token validation.
    ///
    /// These authorization addresses are independent of the transport's bind address or
    /// dial target. An empty list rejects connection requests with an explicit error.
    /// For port-zero binds, install the observed address with
    /// [`NetcodeServer::set_expected_addresses`] before clients connect.
    pub expected_addresses: Vec<SocketAddr>,
    pub connection_request_handler: Option<Arc<dyn ConnectionRequestHandler>>,
}

impl Default for NetcodeConfig {
    fn default() -> Self {
        Self {
            max_clients: MAX_CLIENTS,
            num_disconnect_packets: 10,
            keep_alive_send_rate: 1.0 / 10.0,
            client_timeout_secs: 3,
            protocol_id: 0,
            private_key: [0; PRIVATE_KEY_BYTES],
            expected_addresses: Vec::new(),
            connection_request_handler: None,
        }
    }
}

impl NetcodeConfig {
    pub fn with_max_clients(mut self, max_clients: usize) -> Self {
        self.max_clients = max_clients;
        self
    }

    pub fn with_protocol_id(mut self, protocol_id: u64) -> Self {
        self.protocol_id = protocol_id;
        self
    }
    pub fn with_key(mut self, key: Key) -> Self {
        self.private_key = key;
        self
    }

    pub fn with_client_timeout_secs(mut self, client_timeout_secs: i32) -> Self {
        self.client_timeout_secs = client_timeout_secs;
        self
    }

    /// Set the socket addresses accepted during private connect-token validation.
    ///
    /// An empty list rejects connection requests.
    pub fn with_expected_addresses(
        mut self,
        addresses: impl IntoIterator<Item = SocketAddr>,
    ) -> Self {
        self.expected_addresses = addresses.into_iter().collect();
        self
    }

    pub fn with_connection_request_handler(
        mut self,
        handler: Arc<dyn ConnectionRequestHandler>,
    ) -> Self {
        self.connection_request_handler = Some(handler);
        self
    }
}

impl NetcodeServer {
    pub fn new(config: NetcodeConfig) -> Self {
        let context = NetcodeServerContext::default();
        let mut cfg = ServerConfig::with_context(context)
            .on_connect(|id, entity, user_data, ctx| {
                ctx.connections.push((id, entity, user_data));
            })
            .on_disconnect(|id, entity, ctx| {
                ctx.disconnections.push((id, entity));
            });
        cfg = cfg.max_clients(config.max_clients);
        cfg = cfg.keep_alive_send_rate(config.keep_alive_send_rate);
        cfg = cfg.num_disconnect_packets(config.num_disconnect_packets);
        cfg = cfg.client_timeout_secs(config.client_timeout_secs);
        cfg = cfg.expected_addresses(config.expected_addresses);
        if let Some(handler) = config.connection_request_handler {
            cfg = cfg.connection_request_handler(handler);
        }
        let server =
            crate::server::Server::with_config(config.protocol_id, config.private_key, cfg)
                .expect("Could not create server netcode");
        Self { inner: server }
    }

    pub fn set_connection_request_handler(&mut self, handler: Arc<dyn ConnectionRequestHandler>) {
        self.inner.set_connection_request_handler(handler);
    }

    /// Replace the socket addresses accepted during private connect-token validation.
    ///
    /// Use this after a port-zero bind to explicitly authorize the observed address,
    /// before clients connect. An empty list rejects new connection requests.
    pub fn set_expected_addresses(&mut self, addresses: impl IntoIterator<Item = SocketAddr>) {
        self.inner.set_expected_addresses(addresses);
    }

    /// Clears the Netcode runtime state while preserving this server's configuration.
    ///
    /// This is invoked automatically when the server enters [`Stopped`].
    pub fn reset(&mut self) {
        self.inner.reset();
        self.inner.cfg.context.connections.clear();
        self.inner.cfg.context.disconnections.clear();
    }
}

impl NetcodeServerPlugin {
    fn admit_connection(
        world: &mut World,
        server_entity: Entity,
        entity: Entity,
        id: ClientId,
        user_data: [u8; USER_DATA_BYTES],
    ) {
        if world.get_entity(entity).is_err() {
            if let Some(mut server) = world.get_mut::<NetcodeServer>(server_entity) {
                server.inner.remove_by_entity(entity);
            }
            return;
        }
        let local = LocalId(PeerId::SERVER);
        let remote = RemoteId(PeerId(id));
        let mismatch = world
            .get::<LocalId>(entity)
            .is_some_and(|requested| *requested != local)
            || world
                .get::<RemoteId>(entity)
                .is_some_and(|requested| *requested != remote);
        if id == 0 {
            reject(
                world,
                entity,
                alloc::format!("{}", crate::error::Error::ReservedClientId),
            );
        } else if mismatch {
            reject(
                world,
                entity,
                alloc::format!(
                    "requested identity does not match authenticated netcode identity {:?}",
                    remote.0
                ),
            );
        } else {
            world
                .entity_mut(entity)
                .insert((ClientOf, TokenUserData(user_data)));
            if admit(world, entity, local, remote, ()) {
                return;
            }
        }
        if let Some(mut server) = world.get_mut::<NetcodeServer>(server_entity) {
            server.inner.remove_by_entity(entity);
        }
    }

    /// Takes packets from the Link, process them through the server,
    /// and buffer them back into the link to be sent by the IO
    fn send(
        mut server_query: Query<(&mut NetcodeServer, &Endpoint), (With<Server>, Without<Stopped>)>,
        client_query: Query<
            (
                Entity,
                &mut Link,
                Option<&RemoteId>,
                Option<&Connected>,
                Option<&Disconnecting>,
            ),
            (With<LinkOf>, Without<HostClient>),
        >,
    ) {
        // TODO: we should be able to do ParIterMut if we can make the code understand
        //  that the transports/links are all mutually exclusive...
        //  Maybe some unsafe Cloneble wrapper around the client_query?
        //  Or maybe store the clients into a Local<Vec<(&mut Transport, &mut Link)>>? so that we can iterate faster through them?
        // Each Link is uniquely associated with one server, so parallel workers can safely share
        // the query before taking their disjoint unsafe reborrows below.
        let client_query = &client_query;
        let server_query = adaptive_for_each_mut!(server_query);
        server_query
            // .iter_mut()
            .for_each(|(mut netcode_server, server)| {
                // SAFETY: we know that each client is unique to a single server so we won't
                //  violate aliasing rules
                let mut client_query = unsafe { client_query.reborrow_unsafe() };

                // SAFETY: we know that the entities of a relationship are unique
                let unique_slice =
                    unsafe { UniqueEntitySlice::from_slice_unchecked(server.collection()) };
                client_query.iter_many_unique_mut(unique_slice).for_each(
                    |(entity, mut link, remote_id, connected, disconnecting)| {
                        // If the client was connected, it has a Netcode client_id
                        if connected.is_some() {
                            if let Some(client_id) = remote_id.map(|id| id.0.0) {
                                for _ in 0..link.send.len() {
                                    if let Some(payload) = link.send.pop() {
                                        netcode_server
                                            .inner
                                            .send(payload, client_id, &mut link.send)
                                            .inspect_err(|e| {
                                                error!("Error sending packet: {:?}", e);
                                            })
                                            .ok();
                                    }
                                }

                                // NOTE: we send any netcode packets AFTER the user payloads have been processed
                                // (because we want the
                                netcode_server
                                    .inner
                                    .send_keepalives(client_id, &mut link.send)
                                    .inspect_err(|e| {
                                        error!("Error sending keepalive packet: {:?}", e);
                                    })
                                    .ok();
                            } else {
                                error!(
                                    "The client is Connected but does not have a RemoteId component"
                                );
                            }
                        } else {
                            // if the client is not connected, remove any messages buffered in link.send
                            // We don't want to allow users to send messages while not connected
                            //
                            // However if we are disconnecting, we still want to send the disconnect packets
                            // (we don't use `send_netcode_packets` because we need to remove the client from `send_queue`)
                            if disconnecting.is_none() {
                                link.send.drain();
                            }
                        }

                        // even if it was not connected, we might need to send the netcode packets that were buffered
                        netcode_server
                            .inner
                            .send_netcode_packets(entity, &mut link.send);

                        // #[cfg(feature = "test_utils")]
                        // trace!("SERVER: length of each packet in send: {:?}", link.send.iter().map(|p| p.len()).collect::<Vec<_>>());
                    },
                );
            })
    }

    /// Receive packets from the Link, process them through the server,
    /// then buffer them back into the Link
    fn receive(
        parallel_commands: ParallelCommands,
        real_time: Res<Time<Real>>,
        mut server_query: Query<
            (Entity, &mut NetcodeServer, &mut Endpoint, Has<Stopping>),
            Without<Stopped>,
        >,
        link_query: Query<(Entity, &mut Link), (With<LinkOf>, Without<HostClient>)>,
    ) {
        let delta = real_time.delta();

        // Each Link is uniquely associated with one server, so parallel workers can safely share
        // the query before taking their disjoint unsafe reborrows below.
        let link_query = &link_query;

        // receive packets from the link and process them through the server
        let server_query = adaptive_for_each_mut!(server_query);
        server_query.for_each(
            |(server_entity, mut netcode_server, mut server, stopping)| {
                parallel_commands.command_scope(|mut c| {
                    // SAFETY: we know that each client is unique to a single server so we won't
                    //  violate aliasing rules
                    let mut link_query = unsafe { link_query.reborrow_unsafe() };

                    netcode_server.inner.update_state(delta.as_secs_f64());

                    // TODO: try to make this parallel!
                    // enable split borrows
                    let server = &mut *server;
                    // SAFETY: we know that the list of client entities are unique because it is a Relationship
                    let unique_slice =
                        unsafe { UniqueEntitySlice::from_slice_unchecked(server.collection()) };
                    link_query
                        .iter_many_unique_mut(unique_slice)
                        .for_each(|(entity, mut link)| {
                            // Timeout callbacks already scheduled this link for retirement.
                            // Buffered retries must not recreate a reservation before it despawns.
                            if netcode_server
                                .inner
                                .cfg
                                .context
                                .disconnections
                                .iter()
                                .any(|(_, disconnected)| *disconnected == entity)
                            {
                                return;
                            }
                            let mut entity_mut = c.entity(entity);

                            // #[cfg(feature = "test_utils")]
                            // trace!("SERVER: length of each packet in receive: {:?}", link.recv.iter().map(|p| p.len()).collect::<Vec<_>>());

                            // TODO: insert Connecting if we receive a ConnectionRequest packet
                            match netcode_server.inner.receive(link.as_mut(), &mut entity_mut) {
                                Ok(errors) => {
                                    for error in errors {
                                        error.log();
                                        c.write_message(NetcodeServerError {
                                            server_entity,
                                            client_entity: entity,
                                            error,
                                        });
                                    }
                                }
                                Err(error) => {
                                    error!("Error receiving packet: {:?}", error);
                                    c.write_message(NetcodeServerError {
                                        server_entity,
                                        client_entity: entity,
                                        error,
                                    });
                                }
                            }
                        });

                    // Connections: we know the connection comes from the current entity!
                    netcode_server
                        .inner
                        .cfg
                        .context
                        .connections
                        .drain(..)
                        .for_each(|(id, entity, user_data)| {
                            // TODO: mention server id in case we have multiple servers
                            info!("New connection on netcode from {:?} ({:?})", id, entity);
                            trace!("Adding Connected/ClientOf with id {:?}", id);
                            c.queue(move |world: &mut World| {
                                Self::admit_connection(world, server_entity, entity, id, user_data);
                            });
                        });
                    netcode_server
                        .inner
                        .cfg
                        .context
                        .disconnections
                        .drain(..)
                        .for_each(|(id, entity)| {
                            // TODO: mention server id in case we have multiple servers
                            info!(
                                "Disconnection from netcode client {:?}. Despawning entity.",
                                id
                            );
                            // first disconnect to trigger observers
                            c.entity(entity).try_insert((
                                Disconnected {
                                    reason: DisconnectedReason::ByPeer(None),
                                },
                                RetireNetcodeLink,
                            ));
                        });
                    if stopping {
                        // after we sent disconnection packets, we can stop the server transport
                        c.trigger(Unlink {
                            entity: server_entity,
                            reason: UnlinkReason::ServerStopped,
                        });
                        c.entity(server_entity).insert(Stopped);
                    }
                });
            },
        )
    }

    fn start(trigger: On<Start>, query: Query<(), With<NetcodeServer>>, mut commands: Commands) {
        if query.get(trigger.entity).is_ok() {
            let entity = trigger.entity;
            commands.queue(move |world: &mut World| {
                lightyear_connection::server::start_server(world, entity);
            });
        }
    }

    fn reset_on_stopped(trigger: On<Add, Stopped>, mut query: Query<&mut NetcodeServer>) {
        if let Ok(mut server) = query.get_mut(trigger.entity) {
            server.reset();
        }
    }

    fn remove_link(
        trigger: On<Remove, LinkOf>,
        links: Query<&LinkOf>,
        mut servers: Query<&mut NetcodeServer>,
    ) {
        if let Ok(link) = links.get(trigger.entity) {
            if let Ok(mut server) = servers.get_mut(link.endpoint) {
                server.inner.remove_by_entity(trigger.entity);
            }
        }
    }

    fn disconnected(
        trigger: On<Insert, Disconnected>,
        links: Query<&LinkOf>,
        mut servers: Query<&mut NetcodeServer>,
        mut commands: Commands,
    ) {
        if let Ok(link) = links.get(trigger.entity)
            && let Ok(mut server) = servers.get_mut(link.endpoint)
            && server.inner.remove_by_entity(trigger.entity)
        {
            // Transport failure can precede netcode's timeout. Retire the entity as well as
            // its session, since that timeout can no longer perform the cleanup.
            commands.entity(trigger.entity).insert(RetireNetcodeLink);
        }
    }

    fn retire_links(links: Query<Entity, With<RetireNetcodeLink>>, mut commands: Commands) {
        for entity in &links {
            commands.entity(entity).despawn();
        }
    }

    fn stop(
        trigger: On<Stop>,
        mut commands: Commands,
        mut query: Query<(Entity, &mut NetcodeServer, &Endpoint), Without<Stopped>>,
        mut link_query: Query<
            (Entity, &mut Link, &RemoteId),
            (With<ClientOf>, With<Connected>, Without<HostClient>),
        >,
    ) -> Result {
        if let Ok((server_entity, mut netcode_server, server)) = query.get_mut(trigger.entity) {
            info!("Stopping netcode server");

            commands.entity(server_entity).insert(Stopping);

            // SAFETY: we know that the list of client entities are unique because it is a Relationship
            let unique_slice =
                unsafe { UniqueEntitySlice::from_slice_unchecked(server.collection()) };
            link_query.iter_many_unique_mut(unique_slice).try_for_each(
                |(entity, mut link, remote_peer_id)| -> Result {
                    let client_id = remote_peer_id.0.0;
                    // this will make sure that `netcode.on_disconnect` is called, so the entity will get disconnected
                    // in the next frame from the `receive` system.
                    netcode_server.inner.disconnect(client_id, &mut link.send)?;
                    commands.entity(entity).insert(Disconnecting);
                    Ok(())
                },
            )?;
        }
        Ok(())
    }
}
#[cfg(all(test, feature = "client"))]
mod tests {
    use super::*;
    use lightyear_connection::network_topology::NetworkingMetadata;
    use lightyear_link::recv_payload_from_bytes;

    #[test]
    fn duplicate_global_admission_removes_netcode_session() {
        let mut app = App::new();
        app.set_error_handler(|error, _| panic!("lifecycle command failed: {error}"));
        // A transport closes its link in response to Unlink. Its deferred state cleanup must
        // complete before netcode retires the accepted entity.
        app.add_observer(|event: On<Unlink>, mut commands: Commands| {
            commands
                .entity(event.entity)
                .insert(lightyear_link::Unlinked {
                    reason: event.reason.clone(),
                });
        });
        app.init_resource::<Time<Real>>();
        app.add_plugins(NetcodeServerPlugin);
        #[derive(Resource, Default)]
        struct Rejections(Vec<Entity>);
        app.init_resource::<Rejections>();
        app.add_observer(
            |event: On<Insert, Disconnected>,
             disconnected: Query<&Disconnected>,
             mut rejections: ResMut<Rejections>| {
                if matches!(
                    disconnected.get(event.entity).unwrap().reason,
                    DisconnectedReason::TransportError(_)
                ) {
                    rejections.0.push(event.entity);
                }
            },
        );
        let server = app
            .world_mut()
            .spawn(NetcodeServer::new(NetcodeConfig {
                expected_addresses: alloc::vec!["127.0.0.1:5000".parse().unwrap()],
                ..Default::default()
            }))
            .id();
        app.world_mut().flush();
        app.world_mut().trigger(Start { entity: server });
        app.world_mut().flush();

        let incumbent = app.world_mut().spawn_empty().id();
        assert!(admit(
            app.world_mut(),
            incumbent,
            LocalId(PeerId(1)),
            RemoteId(PeerId(7)),
            (),
        ));
        let incoming = app
            .world_mut()
            .spawn((Link::default(), LinkOf { endpoint: server }))
            .id();
        let token = crate::ConnectToken::build("127.0.0.1:5000", 0, 7, [0; PRIVATE_KEY_BYTES])
            .generate()
            .unwrap()
            .try_into_bytes()
            .unwrap();
        let mut client = crate::client::Client::new(&token).unwrap();
        let mut client_link = Link::default();
        client.connect();
        for _ in 0..4 {
            client.try_update(0.2, &mut client_link.recv).unwrap();
            client.drain_send_netcode_packets(&mut client_link.send);
            {
                let mut link = app.world_mut().get_mut::<Link>(incoming).unwrap();
                while let Some(packet) = client_link.send.pop() {
                    link.recv.push_raw(recv_payload_from_bytes(packet));
                }
            }
            app.update();
            let Some(mut link) = app.world_mut().get_mut::<Link>(incoming) else {
                break;
            };
            while let Some(packet) = link.send.pop() {
                client_link.recv.push_raw(recv_payload_from_bytes(packet));
            }
        }

        assert_eq!(
            app.world()
                .resource::<NetworkingMetadata>()
                .peer_map
                .get(&PeerId(7)),
            Some(&incumbent),
        );
        assert!(app.world().get::<Connected>(incumbent).is_some());
        assert!(app.world().get::<Connected>(incoming).is_none());
        assert_eq!(app.world().resource::<Rejections>().0, [incoming]);
        assert!(app.world().get_entity(incoming).is_err());
        assert!(
            app.world()
                .get::<NetcodeServer>(server)
                .unwrap()
                .inner
                .client_ids()
                .next()
                .is_none()
        );
    }
}

impl Plugin for NetcodeServerPlugin {
    fn build(&self, app: &mut App) {
        if !app.is_plugin_added::<lightyear_connection::client::ConnectionPlugin>() {
            app.add_plugins(lightyear_connection::client::ConnectionPlugin);
        }
        if !app.is_plugin_added::<lightyear_connection::server::ConnectionPlugin>() {
            app.add_plugins(lightyear_connection::server::ConnectionPlugin);
        }
        app.configure_sets(
            PreUpdate,
            (
                LinkSystems::Receive,
                ConnectionSystems::Receive,
                TransportSystems::Receive,
            )
                .chain(),
        );
        app.configure_sets(
            PostUpdate,
            (
                TransportSystems::Send,
                ConnectionSystems::Send,
                LinkSystems::Send,
            )
                .chain(),
        );

        app.add_systems(PreUpdate, Self::receive.in_set(ConnectionSystems::Receive));
        app.add_systems(PostUpdate, Self::send.in_set(ConnectionSystems::Send));
        app.add_systems(Last, Self::retire_links);

        app.add_message::<NetcodeServerError>();

        app.add_observer(Self::start);
        app.add_observer(Self::stop);
        app.add_observer(Self::reset_on_stopped);
        app.add_observer(Self::remove_link);
        app.add_observer(Self::disconnected);
    }
}
